import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { startHqServer } from './server.mjs';
const { seedIDs } = await import('../../backend/src/hq-mock/seed.ts');
const runtime = await startHqServer({port:0,storageDir:false,autoAdvance:false});
const browser = await chromium.launch({headless:true});
try {
 for (const viewport of [{width:320,height:700},{width:390,height:844}]) {
  const context = await browser.newContext({viewport,locale:'ko-KR',serviceWorkers:'block'});
  const page = await context.newPage();
  let submitAttempts=0;
  await page.route('**/api/orders/*/submit',route=>{submitAttempts++;return route.abort()});
  await page.goto(runtime.url+'/orders');
  await page.locator('main.h06-order-page').waitFor();
  await page.locator('.h06-order-results-heading').getByText('검색 결과').waitFor();
  assert.ok(await page.locator('.h06-order-results-heading').evaluate(e=>{const prior=e.previousElementSibling;return prior&&e.getBoundingClientRect().top-prior.getBoundingClientRect().bottom>=20}),'검색 조건과 결과 사이 간격');
  assert.equal(await page.locator('.h06-order-page > h1').evaluate(el=>getComputedStyle(el).color),'rgb(255, 255, 255)','모바일 주문 제목 대비');
  assert.equal(await page.locator('.h06-order-page > h1 .dio-workspace-icon').evaluate(el=>getComputedStyle(el).color),'rgb(18, 74, 166)','모바일 주문 아이콘 대비');
  await page.getByLabel('고객 검색').fill('없는 테스트 고객');
  await page.getByText('조건에 맞는 주문이 없습니다.').waitFor();
  await page.getByLabel('고객 검색').fill('');
  await page.getByLabel('주문 상태').selectOption('DRAFT');
  await page.getByLabel('주문 상태').selectOption('');
  await page.getByLabel('주문일 시작').fill('2026-01-01');
  await page.getByLabel('주문일 종료').fill('2026-12-31');
  await page.getByLabel('계약 검색').fill('본사');
  await page.getByLabel('담당자 ID').fill('1');
  await page.getByLabel('품목 검색').fill('테스트');
  for(const field of ['주문일 시작','주문일 종료','계약 검색','담당자 ID','품목 검색'])await page.getByLabel(field).fill('');
  await page.getByRole('button',{name:'새 주문',exact:true}).click();
  await page.getByLabel('승인 계약').selectOption(seedIDs.approvedContract);
  const created = page.waitForResponse(r=>new URL(r.url()).pathname==='/api/orders'&&r.request().method()==='POST');
  await page.getByRole('button',{name:'주문 초안 만들기'}).click();
  const order = await (await created).json();
  await page.getByLabel('품목 유형').selectOption('PRODUCT');
  await page.getByLabel('분류').fill('');
  await page.getByLabel('품목 검색').fill('ab');
  assert.equal(await page.getByLabel('ERP 품목').isDisabled(),true);
  await page.getByLabel('품목 검색').fill('');
  await page.getByLabel('ERP 품목').selectOption(seedIDs.product);
  await page.getByLabel('수량',{exact:true}).fill('1.5');
  assert.equal(await page.getByRole('button',{name:'품목 추가'}).isDisabled(),true,'소수 수량 추가 차단');
  await page.getByText('수량은 1부터 9,999까지의 정수로 입력해 주세요.').waitFor();
  await page.getByLabel('수량',{exact:true}).fill('10000');
  assert.equal(await page.getByRole('button',{name:'품목 추가'}).isDisabled(),true,'최대 수량 초과 차단');
  await page.getByLabel('수량',{exact:true}).fill('1');
  const added = page.waitForResponse(r=>new URL(r.url()).pathname===`/api/orders/${order.public_id}/items`&&r.request().method()==='POST');
  await page.getByRole('button',{name:'품목 추가'}).click(); assert.equal((await added).status(),200);
  const item = page.locator('.h06-line').filter({has:page.getByRole('button',{name:'수량 저장'})});
  await item.getByRole('spinbutton').fill('3');
  const updated = page.waitForResponse(r=>r.request().method()==='PATCH' && /\/items\//.test(new URL(r.url()).pathname));
  await item.getByRole('button',{name:'수량 저장'}).click();
  assert.equal((await updated).status(),200);
  await page.getByLabel('배송 방식').selectOption('DIRECT');
  await page.getByRole('button',{name:'직송지 목록 새로 고침'}).click();
  await page.getByLabel('배송 방식').selectOption('LAB');
  assert.equal(await page.getByRole('button',{name:'배송 저장'}).isDisabled(),true,'기공소 미선택 저장 차단');
  await page.getByLabel('배송 방식').selectOption('DIRECT');
  assert.ok(await page.getByLabel('배송지',{exact:true}).evaluate(e=>e.getBoundingClientRect().height)>=44,'배송지 터치 영역');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'가로 넘침 없음');
  await page.getByLabel('배송지',{exact:true}).fill('테스트 배송지 123');
  await page.getByLabel('수령자명').fill('테스트 수령자');
  await page.getByLabel('수령자 전화').fill('010-0000-1234');
  await page.getByLabel('우편번호').fill('12345');
  await page.getByLabel('비고',{exact:true}).fill('격리 목업 시험');
  await page.getByLabel('특급 배송').check();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'목록으로',exact:true}).click();
  assert.equal(await page.getByLabel('수령자명').inputValue(),'테스트 수령자','이탈 취소 시 입력 보존');
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'배송 정보 최신 조회'}).click();
  assert.equal(await page.getByLabel('수령자명').inputValue(),'테스트 수령자','조회 취소 시 입력 보존');
  const failSave = route => route.request().method() === 'PATCH' ? route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({error:'VERSION_CONFLICT'})}) : route.continue();
  await page.route('**/api/orders/*/delivery',failSave);
  const conflict=page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url().endsWith('/delivery'));
  await page.getByRole('button',{name:'배송 저장'}).click();assert.equal((await conflict).status(),409);
  await page.getByRole('alert').first().waitFor();
  assert.equal(await page.getByLabel('수령자명').inputValue(),'테스트 수령자');
  assert.equal(await page.getByLabel('수령자 전화').inputValue(),'010-0000-1234');
  assert.equal(await page.getByLabel('우편번호').inputValue(),'12345');
  await page.unroute('**/api/orders/*/delivery',failSave);
  const delivery = page.waitForResponse(r=>r.request().method()==='PATCH' && r.url().endsWith('/delivery'));
  await page.getByRole('button',{name:'배송 저장'}).click(); assert.equal((await delivery).status(),200);
  await page.reload();
  await page.getByLabel('배송지',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('배송지',{exact:true}).inputValue(),'테스트 배송지 123');
  assert.equal(await page.getByLabel('수령자명').inputValue(),'테스트 수령자');
  assert.equal(await page.getByLabel('수령자 전화').inputValue(),'010-0000-1234');
  assert.equal(await page.getByLabel('우편번호').inputValue(),'12345');
  assert.equal(await page.getByLabel('비고',{exact:true}).inputValue(),'격리 목업 시험');
  assert.equal(await page.getByLabel('특급 배송').isChecked(),true);
  assert.equal(await page.locator('.h06-line').getByRole('spinbutton').inputValue(),'3');
  const removed = page.waitForResponse(r=>r.request().method()==='DELETE' && /\/items\//.test(new URL(r.url()).pathname));
  await page.locator('.h06-line').getByRole('button',{name:'삭제',exact:true}).click(); assert.equal((await removed).status(),200);
  await page.getByText('품목을 추가하세요.').waitFor();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'주문 초안 삭제'}).click();
  await page.getByRole('heading',{name:'주문 상세'}).waitFor();
  page.once('dialog',dialog=>dialog.accept());
  const deleted = page.waitForResponse(r=>new URL(r.url()).pathname===`/api/orders/${order.public_id}`&&r.request().method()==='DELETE');
  await page.getByRole('button',{name:'주문 초안 삭제'}).click(); assert.equal((await deleted).status(),200);
  await page.getByRole('heading',{name:'주문 목록'}).waitFor();
  await page.reload();
  const rows = await page.evaluate(async()=>{const r=await fetch('/api/orders',{headers:{Authorization:`Bearer ${sessionStorage.getItem('dio_crm_hq_access_token')}`}});return r.json()});
  assert.equal(rows.some(row=>row.public_id===order.public_id),false);
  assert.equal(submitAttempts,0,'ERP 주문 전송 없음');
  console.log(`PASS ${viewport.width}: create, edit and reload delivery, item quantity and removal, cancel and delete`);
  await context.close();
 }
} finally { await browser.close();runtime.server.closeAllConnections();await runtime.close(); }
