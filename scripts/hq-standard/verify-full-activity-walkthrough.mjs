import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const folder=path.resolve('docs/crm-activity/full-walkthrough-20261108');
const summary=JSON.parse(fs.readFileSync(path.join(folder,'summary.json'),'utf8'));
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',timeout:120000});
const evidence={};
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',err=>errors.push(err.message));
  await page.goto(pathToFileURL(path.join(folder,'index.html')).href,{waitUntil:'load',timeout:120000});
  console.log('HTML loaded');
  assert.equal(await page.locator('.case').count(),summary.records);
  assert.equal(await page.locator('.case img').count(),summary.imageCount);
  const sizes=await page.locator('.case img').evaluateAll(async imgs=>{const chosen=imgs.filter((_,i)=>i%30===0||i===imgs.length-1);return Promise.all(chosen.map(async img=>{img.loading='eager';await img.decode();return img.naturalWidth>0&&img.naturalHeight>0;}));});
  assert.ok(sizes.every(Boolean));evidence.sampleImagesDecoded=sizes.length;
  const embedded=[...fs.readFileSync(path.join(folder,'index.html'),'utf8').matchAll(/data:image\/png;base64,([A-Za-z0-9+/=]+)/g)];
  assert.equal(embedded.length,summary.imageCount);
  for(const match of embedded){const bytes=Buffer.from(match[1],'base64');assert.equal(bytes.readUInt32BE(0),0x89504e47);assert.ok(bytes.readUInt32BE(16)>0&&bytes.readUInt32BE(20)>0);}
  evidence.embeddedPngHeadersChecked=embedded.length;
  console.log('Image evidence validated',embedded.length);
  await page.locator('#status').selectOption('FAIL');
  assert.equal(await page.locator('.case:visible').count(),summary.count.FAIL);
  await page.locator('#reset').click();
  await page.locator('#device').selectOption('모바일 390×844');
  assert.ok(await page.locator('.case:visible').count()>0);
  assert.equal(await page.locator('.case:visible').evaluateAll(cards=>cards.every(c=>c.dataset.device==='모바일 390×844')),true);
  await page.locator('#search').fill('등록');
  assert.ok(await page.locator('.case:visible').count()>0);
  await page.locator('#reset').click();
  const first=page.locator('.case').filter({has:page.locator('img')}).first();
  await first.locator('summary').click();
  await first.locator('img').first().click();
  assert.ok(await page.locator('#image-view').isVisible());
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#image-view').isVisible(),false);
  evidence.filtersAndImageViewer='PASS';
  await page.locator('#close-captures').click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(folder,'report-preview-pc.png')});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(folder,'report-preview-mobile.png')});
  assert.deepEqual(errors,[]);evidence.pageErrors=errors;evidence.result='PASS';
  fs.writeFileSync(path.join(folder,'html-verification.json'),JSON.stringify(evidence,null,2));
  console.log(JSON.stringify(evidence));
}finally{await Promise.race([browser.close(),new Promise(r=>setTimeout(r,3000))]);}
process.exit(0);
