import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
const root=path.resolve('docs/crm-work-queue/20261108/opportunity/walkthrough');
const summary=JSON.parse(fs.readFileSync(path.join(root,'summary.json'),'utf8'));
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(pathToFileURL(path.join(root,'index.html')).href,{timeout:60000});
assert.equal(await page.locator('.case').count(),summary.steps);
assert.equal(await page.locator('.case img').count(),summary.imageCount);
const bad=await page.locator('.case img').evaluateAll(images=>images.filter(i=>!i.src.startsWith('data:image/png;base64,')).length);assert.equal(bad,0);
await page.locator('.case details').first().evaluate(e=>e.open=true);
const first=page.locator('.case img').first();await first.scrollIntoViewIfNeeded();await first.evaluate(e=>e.decode());await first.click();await page.getByRole('dialog').waitFor();await page.locator('#close').click();
await page.locator('#search').fill('없는검증항목XYZ');assert.equal(await page.locator('.case:visible').count(),0);
await page.locator('#reset').click();await page.locator('#status').selectOption('PASS');assert.equal(await page.locator('.case:visible').count(),summary.counts.PASS);
await page.locator('#reset').click();await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:path.join(root,'html-pc.png')});
await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);assert.equal(overflow,false);await page.screenshot({path:path.join(root,'html-mobile.png')});
const checks={steps:summary.steps,images:summary.imageCount,embeddedPng:true,sampleImageDecode:true,imageViewer:true,filters:true,mobileNoOverflow:true};
fs.writeFileSync(path.join(root,'html-verification.json'),JSON.stringify(checks,null,2));
await Promise.race([browser.close(),new Promise(r=>setTimeout(r,5000))]);console.log(JSON.stringify(checks));process.exit(0);
